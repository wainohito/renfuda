#!/usr/bin/env python3
"""Generates core/JisTables.inc: CP932 (Shift_JIS) and EUC-JP (JIS X 0208
and half-width kana) to Unicode tables for the CSV import (I/O spec 3.2).

The core converts these encodings itself; it does not depend on iconv.

    python3 tools/make_jis_tables.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "core", "JisTables.inc")


def table(rows):
    lines = []
    for row in rows:
        lines.append("\t" + ",".join("0x%04x" % v for v in row) + ",")
    return "\n".join(lines)


def main():
    # CP932 double byte: lead 0x81-0x9f, 0xe0-0xfc; trail 0x40-0xfc.
    leads = list(range(0x81, 0xa0)) + list(range(0xe0, 0xfd))
    cp932 = []
    for lead in leads:
        row = []
        for trail in range(0x40, 0xfd):
            try:
                text = bytes([lead, trail]).decode("cp932")
                row.append(ord(text) if len(text) == 1 else 0)
            except UnicodeDecodeError:
                row.append(0)
        cp932.append(row)
    # EUC-JP JIS X 0208: both bytes 0xa1-0xfe.
    euc = []
    for first in range(0xa1, 0xff):
        row = []
        for second in range(0xa1, 0xff):
            try:
                text = bytes([first, second]).decode("euc_jp")
                row.append(ord(text) if len(text) == 1
                           and ord(text) <= 0xffff else 0)
            except UnicodeDecodeError:
                row.append(0)
        euc.append(row)
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("// Generated by tools/make_jis_tables.py. Do not edit.\n")
        f.write("// CP932: [lead index][trail - 0x40], lead index 0-30 for "
                "0x81-0x9f,\n// 31-59 for 0xe0-0xfc. 0 = no character.\n")
        f.write("static const uint16_t kCp932Table[%d][%d] = {\n"
                % (len(cp932), 0xfd - 0x40))
        f.write(table(cp932))
        f.write("\n};\n\n")
        f.write("// EUC-JP (JIS X 0208): [first - 0xa1][second - 0xa1].\n")
        f.write("static const uint16_t kEucJpTable[94][94] = {\n")
        f.write(table(euc))
        f.write("\n};\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
